export function buildP76GuidanceTutorials(ledger) {
	return ledger.entries.map(entry => ({
		id: entry.tutorialId,
		keywords: entry.owner.replace(/Scenes$/, "").replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase().split(" "),
		owner: entry.owner,
		pages: (entry.storyboards.length
			? entry.storyboards.map(storyboard => ({
				body: `Goal: reproduce ${storyboard.id}.\n\n1. Gather the blocks shown by this Create family.\n2. Build and power the arrangement.\n3. Observe the expected ${storyboard.method} behavior.\n\nIf it does not run, inspect speed, stress, filters, and available inventory with Engineer's Goggles.`,
				bodyZh: `目标：复现 ${storyboard.id}。\n\n1. 准备该 Create 功能族所需方块。\n2. 完成搭建并提供动力。\n3. 检查 ${storyboard.method} 的预期行为。\n\n若设备未运行，请用工程师护目镜检查转速、应力、过滤器和库存。`,
				id: storyboard.id,
				title: storyboard.id.replaceAll("_", " "),
				titleZh: storyboard.id.replaceAll("_", " ")
			}))
			: [{ body: "This Java Ponder family has no directly registered storyboard. Its observable behavior is covered by the owning Bedrock feature and platform checklist.", bodyZh: "该 Java Ponder 功能族没有直接注册的分镜；其可观察行为由对应 Bedrock 功能和平台清单覆盖。", id: `${entry.owner}:overview`, title: "Overview", titleZh: "概览" }])
			.map(page => {
				const key = `createbedrock.guide.page.${entry.owner.replace(/Scenes$/, "").replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase()}.${page.id.replace(/[^a-zA-Z0-9_]/g, "_").toLowerCase()}`;
				return { ...page, bodyKey: `${key}.body`, titleKey: `${key}.title` };
			}),
		source: entry.source
	}));
}

export function renderP76GuidanceCatalog(tutorials) {
	return `// Generated by tools/generate-p7-6-guidance.mjs.\nexport const CREATE_GUIDANCE_SCHEMA_VERSION = 1;\nexport const CREATE_GUIDANCE_TUTORIALS = Object.freeze(${JSON.stringify(tutorials, null, 2)});\n`;
}

export function renderP76GuidanceLanguage(tutorials, locale) {
	const chinese = locale === "zh_CN";
	const lines = ["## P7.6_GENERATED_GUIDANCE_START"];
	for (const tutorial of tutorials)
		for (const page of tutorial.pages) {
			lines.push(`${page.titleKey}=${chinese ? page.titleZh : page.title}`);
			lines.push(`${page.bodyKey}=${(chinese ? page.bodyZh : page.body).replaceAll("\n", "\\n")}`);
		}
	lines.push("## P7.6_GENERATED_GUIDANCE_END");
	return `${lines.join("\n")}\n`;
}
