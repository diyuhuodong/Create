import { cp, mkdir, readFile, stat } from "node:fs/promises";
import { dirname, extname, resolve } from "node:path";

import { P76_PARTICLE_IDS } from "./p7-6-catalogs.mjs";

export const P76_ANIMATION_IDS = Object.freeze([
	"belt_scroll", "kinetic_rotation", "machine_cycle", "tank_liquid", "train_bogey", "equipment_idle"
]);

function clone(value) {
	return JSON.parse(JSON.stringify(value));
}

export function buildP76SoundCatalog(javaSounds) {
	const entries = Object.entries(javaSounds).map(([id, definition]) => {
		const sounds = (definition.sounds ?? []).map(sound => typeof sound === "string" ? { name: sound, type: "file" } : sound);
		const customFiles = sounds.filter(sound => sound.type !== "event" && sound.name?.startsWith("create:"))
			.map(sound => `sounds/create/${sound.name.slice("create:".length)}`);
		const vanillaEvents = sounds.filter(sound => sound.type === "event").map(sound => sound.name.replace(/^minecraft:/, ""));
		return {
			bedrockId: `createbedrock:${id}`,
			customFiles,
			id,
			relation: customFiles.length && vanillaEvents.length ? "composite" : customFiles.length ? "custom_ogg" : vanillaEvents.length ? "vanilla_mix" : "silent_not_applicable",
			source: `src/generated/resources/assets/create/sounds.json#${id}`,
			status: "static_verified",
			subtitle: definition.subtitle,
			vanillaEvents
		};
	}).sort((left, right) => left.id.localeCompare(right.id));
	return { entries, schemaVersion: 1, summary: { events: entries.length, relations: Object.fromEntries(["custom_ogg", "vanilla_mix", "composite", "silent_not_applicable"].map(relation => [relation, entries.filter(entry => entry.relation === relation).length])) } };
}

export function renderP76SoundDefinitions(catalog) {
	const soundDefinitions = {};
	for (const entry of catalog.entries) {
		const sounds = entry.customFiles.length ? entry.customFiles : ["sounds/create/confirm_2"];
		soundDefinitions[entry.bedrockId] = { category: "block", max_distance: 64, sounds };
	}
	return { format_version: "1.20.20", sound_definitions: soundDefinitions };
}

export function renderP76RuntimeSoundCatalog(catalog) {
	const mappings = Object.fromEntries(catalog.entries.map(entry => [entry.bedrockId, entry.customFiles.length ? entry.bedrockId : entry.vanillaEvents[0] ?? null]));
	return `// Generated by tools/generate-p7-6-resources.mjs.\nexport const CREATE_SOUND_EVENTS = Object.freeze(${JSON.stringify(mappings, null, 2)});\n`;
}

export function renderP76Particle(id) {
	return {
		format_version: "1.10.0",
		particle_effect: {
			components: {
				"minecraft:emitter_lifetime_once": { active_time: .05 },
				"minecraft:emitter_rate_instant": { num_particles: id.includes("perimeter") ? 8 : 3 },
				"minecraft:particle_appearance_billboard": { facing_camera_mode: "lookat_xyz", size: id.includes("fluid") ? [.08, .08] : [.12, .12], uv: { texture_height: 16, texture_width: 16, uv: [0, 0], uv_size: [16, 16] } },
				"minecraft:particle_expire_if_not_in_blocks": ["minecraft:air", "minecraft:water"],
				"minecraft:particle_initial_speed": id.includes("steam") ? .12 : .04,
				"minecraft:particle_lifetime_expression": { max_lifetime: id.includes("soul") ? 1.2 : .6 },
				"minecraft:particle_motion_dynamic": { linear_acceleration: [0, id.includes("fluid") ? -.04 : .02, 0] }
			},
			description: { basic_render_parameters: { material: "particles_alpha", texture: "textures/particle/particles" }, identifier: `createbedrock:${id}` }
		}
	};
}

export function renderP76Animations() {
	const bones = {
		belt_scroll: ["java_model"],
		equipment_idle: ["projectile"],
		kinetic_rotation: ["java_model", "crushing_wheel", "marker"],
		machine_cycle: ["java_model"],
		tank_liquid: ["java_model"],
		train_bogey: ["marker"]
	};
	return {
		format_version: "1.8.0",
		animations: Object.fromEntries(P76_ANIMATION_IDS.map((id, index) => [`animation.createbedrock.${id}`, {
			animation_length: index % 2 ? 1 : 2,
			bones: Object.fromEntries(bones[id].map(bone => [bone, { rotation: [0, `query.anim_time * ${id === "kinetic_rotation" || id === "train_bogey" ? 360 : id === "equipment_idle" ? 90 : 0}`, 0], position: [0, id === "tank_liquid" || id === "machine_cycle" ? "math.sin(query.anim_time * 180) * 0.25" : 0, 0] }])),
			loop: true
		}]))
	};
}

