async function fileExists(path) {
	try { return (await stat(path)).isFile(); } catch { return false; }
}

export async function stageP76JavaAssets({ ledger, repositoryRoot, resourcePackRoot }) {
	let copied = 0;
	for (const entry of ledger.entries) {
		if (entry.relation !== "direct_copy")
			continue;
		const source = resolve(repositoryRoot, entry.source);
		if (!await fileExists(source))
			throw new Error(`Missing P7.6 direct-copy resource ${entry.source}`);
		let target = resolve(resourcePackRoot, entry.target.replace(/^resource_pack\//, ""));
		if (extname(source) === ".ogg" && extname(target) !== ".ogg")
			target += ".ogg";
		await mkdir(dirname(target), { recursive: true });
		await cp(source, target);
		copied++;
	}
	return copied;
}

export async function loadP76SoundCatalog(repositoryRoot) {
	const javaSounds = JSON.parse(await readFile(resolve(repositoryRoot, "src/generated/resources/assets/create/sounds.json"), "utf8"));
	return buildP76SoundCatalog(clone(javaSounds));
}
