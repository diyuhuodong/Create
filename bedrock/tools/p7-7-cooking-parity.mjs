export const P77_COOKING_PARITY_SCHEMA_VERSION = 1;

function assertObject(value, label) {
	if (!value || typeof value !== "object" || Array.isArray(value))
		throw new TypeError(`P7.7 cooking parity ${label} must be an object`);
}

function assertString(value, label) {
	if (typeof value !== "string" || value.length === 0)
		throw new TypeError(`P7.7 cooking parity ${label} must be a non-empty string`);
}

function exactJson(left, right) {
	return JSON.stringify(left) === JSON.stringify(right);
}

function recipeFromNativeRecord(record) {
	const definition = record.definition?.["minecraft:recipe_furnace"];
	if (!definition)
		throw new Error(`P7.7 cooking parity recipe ${record.id} requires a native furnace definition`);
	if (!Array.isArray(definition.tags) || definition.tags.length === 0 || typeof definition.input !== "string" || typeof definition.output !== "string")
		throw new Error(`P7.7 cooking parity recipe ${record.id} has an invalid Bedrock furnace definition`);
	const issueValues = new Map(record.issues.map(issue => [issue?.kind, issue?.value]));
	// Native recipe records deliberately retain only the Java fields that
	// Bedrock cannot encode. Defaults are Java's 200 ticks and zero XP.
	const processingTicks = issueValues.get("native_furnace_does_not_preserve_cooking_time") ?? 200;
	const experience = issueValues.get("native_furnace_does_not_preserve_experience") ?? 0;
	if (!Number.isInteger(processingTicks) || processingTicks < 1 || !Number.isFinite(experience) || experience < 0)
		throw new Error(`P7.7 cooking parity recipe ${record.id} has invalid Java cooking semantics`);
	const issueKinds = [...new Set(record.issues.map(issue => issue?.kind))].sort();
	if (!issueKinds.some(kind => kind === "native_furnace_does_not_preserve_cooking_time" || kind === "native_furnace_does_not_preserve_experience"))
		throw new Error(`P7.7 cooking parity recipe ${record.id} does not declare a cooking semantic gap`);
	return {
		experience,
		id: `createbedrock:p7_7/cooking/${record.id.slice("create:".length)}`,
		input: definition.input,
		issueKinds,
		output: definition.output,
		processingTicks,
		sourceId: record.id,
		stations: [...definition.tags].sort()
	};
}

export function buildP77CookingParityCatalog(nativeRecipes) {
	assertObject(nativeRecipes, "native recipe document");
	if (!Array.isArray(nativeRecipes.records))
		throw new TypeError("P7.7 cooking parity native recipe records must be an array");
	const recipes = nativeRecipes.records
		.filter(record => record.status === "blocked_platform_semantics")
		.map(recipeFromNativeRecord)
		.sort((left, right) => left.sourceId.localeCompare(right.sourceId));
	const document = {
		schemaVersion: P77_COOKING_PARITY_SCHEMA_VERSION,
		generatedAt: "deterministic",
		generatedFrom: "data/recipes/native.json",
		recipes,
		summary: {
			experienceOverrides: recipes.filter(recipe => recipe.issueKinds.includes("native_furnace_does_not_preserve_experience")).length,
			processingTimeOverrides: recipes.filter(recipe => recipe.issueKinds.includes("native_furnace_does_not_preserve_cooking_time")).length,
			recipes: recipes.length
		}
	};
	validateP77CookingParityCatalog(document);
	return document;
}

export function renderP77CookingParityRecipes(catalog) {
	validateP77CookingParityCatalog(catalog);
	return `// Generated by tools/generate-p7-7-cooking-parity.mjs. Do not edit.\nexport const COOKING_PARITY_RECIPES = Object.freeze(${JSON.stringify(catalog.recipes, null, "\t")});\n`;
}

export function validateP77CookingParityCatalog(catalog) {
	assertObject(catalog, "catalog");
	if (catalog.schemaVersion !== P77_COOKING_PARITY_SCHEMA_VERSION || catalog.generatedAt !== "deterministic" || catalog.generatedFrom !== "data/recipes/native.json")
		throw new Error("P7.7 cooking parity catalog has an invalid schema or provenance");
	if (!Array.isArray(catalog.recipes) || !catalog.summary || typeof catalog.summary !== "object")
		throw new TypeError("P7.7 cooking parity catalog requires recipes and a summary");
	const ids = new Set();
	const sourceIds = new Set();
	for (const recipe of catalog.recipes) {
		assertObject(recipe, "recipe");
		for (const field of ["id", "input", "output", "sourceId"])
			assertString(recipe[field], `recipe ${recipe.sourceId ?? "unknown"} ${field}`);
		if (!Array.isArray(recipe.stations) || recipe.stations.length === 0 || recipe.stations.some(station => typeof station !== "string" || station.length === 0))
			throw new Error(`P7.7 cooking parity recipe ${recipe.sourceId} requires native stations`);
		if (!Array.isArray(recipe.issueKinds) || recipe.issueKinds.length === 0)
			throw new Error(`P7.7 cooking parity recipe ${recipe.sourceId} requires issue kinds`);
		if (!Number.isInteger(recipe.processingTicks) || recipe.processingTicks < 1 || !Number.isFinite(recipe.experience) || recipe.experience < 0)
			throw new Error(`P7.7 cooking parity recipe ${recipe.sourceId} has invalid timing or experience`);
		if (ids.has(recipe.id) || sourceIds.has(recipe.sourceId))
			throw new Error(`P7.7 cooking parity recipe ${recipe.sourceId} is duplicated`);
		ids.add(recipe.id);
		sourceIds.add(recipe.sourceId);
	}
	if (!exactJson(catalog.recipes.map(recipe => recipe.sourceId), [...sourceIds].sort((left, right) => left.localeCompare(right))))
		throw new Error("P7.7 cooking parity recipes must be sorted by Java source identifier");
	const expectedSummary = {
		experienceOverrides: catalog.recipes.filter(recipe => recipe.issueKinds.includes("native_furnace_does_not_preserve_experience")).length,
		processingTimeOverrides: catalog.recipes.filter(recipe => recipe.issueKinds.includes("native_furnace_does_not_preserve_cooking_time")).length,
		recipes: catalog.recipes.length
	};
	if (!exactJson(catalog.summary, expectedSummary))
		throw new Error("P7.7 cooking parity summary is stale");
	return expectedSummary;
}
